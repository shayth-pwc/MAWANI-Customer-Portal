-- Service evaluation backend tables. Apply once through the approved
-- PostgreSQL migration process; CAP must not auto-deploy these physical tables.
CREATE TABLE IF NOT EXISTS public."BTP_TBL_SERVICE_EVALUATION_QUESTIONS" (
  "ID" uuid PRIMARY KEY,
  "APP_ID" varchar(100) NOT NULL,
  "QUESTION_TEXT" varchar(1000) NOT NULL,
  "QUESTION_TEXT_AR" varchar(1000),
  "MIN_SCORE" integer NOT NULL CHECK ("MIN_SCORE" >= 0),
  "MAX_SCORE" integer NOT NULL CHECK ("MAX_SCORE" > "MIN_SCORE"),
  "DISPLAY_ORDER" integer NOT NULL DEFAULT 1 CHECK ("DISPLAY_ORDER" >= 1),
  "ACTIVE_STATUS" boolean NOT NULL DEFAULT true,
  "CREATED_ON" timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "CREATED_BY" uuid,
  "CHANGED_ON" timestamptz,
  "CHANGED_BY" uuid
);

CREATE INDEX IF NOT EXISTS "ix_SERVICE_EVALUATION_QUESTIONS_APP"
  ON public."BTP_TBL_SERVICE_EVALUATION_QUESTIONS" ("APP_ID", "ACTIVE_STATUS", "DISPLAY_ORDER");

CREATE TABLE IF NOT EXISTS public."BTP_TBL_SERVICE_EVALUATIONS" (
  "ID" uuid PRIMARY KEY,
  "REQUEST_UUID" uuid NOT NULL,
  "APP_ID" varchar(100) NOT NULL,
  "USER_UUID" uuid NOT NULL,
  "AVERAGE_SCORE" numeric(10,2) NOT NULL,
  "AVERAGE_PERCENT" numeric(10,2) NOT NULL,
  "QUESTION_COUNT" integer NOT NULL CHECK ("QUESTION_COUNT" > 0),
  "CREATED_ON" timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "CREATED_BY" uuid,
  CONSTRAINT "uq_SERVICE_EVALUATION_REQUEST_APP" UNIQUE ("REQUEST_UUID", "APP_ID")
);

CREATE INDEX IF NOT EXISTS "ix_SERVICE_EVALUATIONS_REPORT"
  ON public."BTP_TBL_SERVICE_EVALUATIONS" ("APP_ID", "CREATED_ON");

CREATE TABLE IF NOT EXISTS public."BTP_TBL_SERVICE_EVALUATION_ANSWERS" (
  "ID" uuid PRIMARY KEY,
  "EVALUATION_ID" uuid NOT NULL REFERENCES public."BTP_TBL_SERVICE_EVALUATIONS" ("ID") ON DELETE RESTRICT,
  "QUESTION_ID" uuid NOT NULL REFERENCES public."BTP_TBL_SERVICE_EVALUATION_QUESTIONS" ("ID") ON DELETE RESTRICT,
  "QUESTION_TEXT" varchar(1000) NOT NULL,
  "QUESTION_TEXT_AR" varchar(1000),
  "MIN_SCORE" integer NOT NULL,
  "MAX_SCORE" integer NOT NULL,
  "SCORE" integer NOT NULL,
  "COMMENT" varchar(2000),
  "CREATED_ON" timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT "ck_SERVICE_EVALUATION_ANSWER_SCORE"
    CHECK ("SCORE" >= "MIN_SCORE" AND "SCORE" <= "MAX_SCORE"),
  CONSTRAINT "uq_SERVICE_EVALUATION_ANSWER" UNIQUE ("EVALUATION_ID", "QUESTION_ID")
);

CREATE INDEX IF NOT EXISTS "ix_SERVICE_EVALUATION_ANSWERS_EVALUATION"
  ON public."BTP_TBL_SERVICE_EVALUATION_ANSWERS" ("EVALUATION_ID");
